from pydantic import BaseModel, Field
from typing import List, Optional

class DetectionMetrics(BaseModel):
    map_50: float = Field(..., ge=0.0, le=1.0, description="Mean Average Precision at IoU=0.50")
    map_50_95: float = Field(..., ge=0.0, le=1.0, description="Mean Average Precision at IoU=0.50:0.95")
    precision: float = Field(..., ge=0.0, le=1.0, description="Precision (TP / (TP + FP))")
    recall: float = Field(..., ge=0.0, le=1.0, description="Recall (TP / (TP + FN))")
    f1_score: float = Field(..., ge=0.0, le=1.0, description="F1 Score (2 * P * R / (P + R))")

class TrackingMetrics(BaseModel):
    mota: float = Field(..., ge=0.0, le=1.0, description="Multiple Object Tracking Accuracy")
    motp: float = Field(..., ge=0.0, le=1.0, description="Multiple Object Tracking Precision")
    idf1: float = Field(..., ge=0.0, le=1.0, description="ID F1 Score")
    id_switches: int = Field(..., ge=0, description="Total count of identity switches")
    mostly_tracked_count: int = Field(..., ge=0, description="Tracks tracked for >= 80% of duration")
    mostly_lost_count: int = Field(..., ge=0, description="Tracks tracked for <= 20% of duration")

class PrivacyMetrics(BaseModel):
    privacy_leakage_rate_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage of unblurred sensitive frames")
    mean_leak_duration_frames: float = Field(..., ge=0.0, description="Mean consecutive unblurred leak frames")
    ghost_recovery_rate_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage of lost tracks recovered by Ghost Box")
    avg_ghost_lifetime_frames: float = Field(..., ge=0.0, description="Average active duration of Ghost Boxes")
    blur_coverage_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage of frame ROI target coverage")
    frames_protected_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage of total video frames fully protected")

class PerformanceMetrics(BaseModel):
    avg_fps: float = Field(..., ge=0.0, description="Average pipeline processing FPS")
    detection_latency_ms: float = Field(..., ge=0.0)
    tracking_latency_ms: float = Field(..., ge=0.0)
    reid_latency_ms: float = Field(..., ge=0.0)
    ghost_latency_ms: float = Field(..., ge=0.0)
    blur_latency_ms: float = Field(..., ge=0.0)
    pipeline_latency_ms: float = Field(..., ge=0.0)
    peak_memory_mb: float = Field(..., ge=0.0, description="Peak RAM / VRAM memory usage in MB")

class EvaluationReport(BaseModel):
    """
    Master JSON-serializable benchmark report generated by EvaluationService.
    """
    task_id: str
    total_frames_evaluated: int
    evaluated_at: str
    benchmark_passed: bool
    detection_metrics: DetectionMetrics
    tracking_metrics: TrackingMetrics
    privacy_metrics: PrivacyMetrics
    performance_metrics: PerformanceMetrics
